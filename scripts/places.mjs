// Builds data/places.mjs, the town list /api/wave uses to name where a wave came
// from ("Lancaster, PA"). Source: GeoNames (https://www.geonames.org/, CC BY 4.0;
// credited in the app's info panel). Only the function reads it; it never ships
// to the browser.
//
//   curl -LO https://download.geonames.org/export/dump/cities5000.zip && unzip cities5000.zip
//   curl -LO https://download.geonames.org/export/dump/admin1CodesASCII.txt
//   curl -LO https://download.geonames.org/export/dump/countryInfo.txt
//   node scripts/places.mjs cities5000.txt admin1CodesASCII.txt countryInfo.txt
//
// A JS module rather than JSON so the function's bundler inlines it with no
// import attributes or extra file config. Each entry is [name, suffix, lat, lon, population, region]: suffix is what follows
// the comma ("PA" in the US, the province or state in Canada and Australia, else
// the country), region is the state or province name for when no town is close.

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const [citiesPath, admin1Path, countryPath] = process.argv.slice(2);
if (!countryPath) {
    console.error('usage: node scripts/places.mjs cities5000.txt admin1CodesASCII.txt countryInfo.txt');
    process.exit(1);
}

const admin1 = new Map(readFileSync(admin1Path, 'utf8').split('\n').filter(Boolean)
    .map(line => { const [code, name] = line.split('\t'); return [code, name]; }));
const countries = new Map(readFileSync(countryPath, 'utf8').split('\n')
    .filter(line => line && !line.startsWith('#'))
    .map(line => { const f = line.split('\t'); return [f[0], f[4]]; }));

// Neighbourhoods, historical, abandoned and destroyed places would name a wave
// after somewhere people don't call home.
const SKIP = new Set(['PPLX', 'PPLH', 'PPLQ', 'PPLW', 'PPLCH']);
const BY_STATE = new Set(['US', 'CA', 'AU']);

const out = [];
for (const line of readFileSync(citiesPath, 'utf8').split('\n')) {
    if (!line) continue;
    const f = line.split('\t');
    const [name, lat, lon, fcode, cc, a1, pop] = [f[1], f[4], f[5], f[7], f[8], f[10], f[14]];
    if (SKIP.has(fcode)) continue;
    const region = admin1.get(`${cc}.${a1}`) || countries.get(cc) || cc;
    const suffix = cc === 'US' ? a1 : BY_STATE.has(cc) ? region : countries.get(cc) || cc;
    out.push([name, suffix, +Number(lat).toFixed(3), +Number(lon).toFixed(3), Number(pop) || 0, region]);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(join(root, 'data', 'places.mjs'),
    '// Generated by scripts/places.mjs from GeoNames (CC BY 4.0). Do not edit.\n' +
    `export default ${JSON.stringify(out)};\n`);
console.log(`wrote data/places.mjs: ${out.length} places`);
